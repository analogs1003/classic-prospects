def build_merged_horses():
    """事前評価馬(70頭)に戦績アップデートを適用し、戦績評価の新規馬(30頭)を統合する。"""
    merged = []
    seen_ids = set()

    for base in HORSES:
        item = dict(base)
        item.setdefault("selection_source", "事前評価(血統/価格)")
        item.setdefault("race_status", "未調査")
        item.setdefault("starts", None)
        item.setdefault("wins", None)
        item.setdefault("major_results", "")

        upd = RACE_UPDATES.get(item["netkeiba_id"])
        if upd:
            item.update(upd)

        merged.append(item)
        seen_ids.add(item["netkeiba_id"])

    for perf in PERFORMANCE_HORSES:
        if perf["netkeiba_id"] in seen_ids:
            continue
        merged.append(dict(perf))
        seen_ids.add(perf["netkeiba_id"])

    return merged


def calculate_score(horse):
    """app.js と同一ロジックでクラシック指数を算出する。"""
    perf_pt = 0
    pre_pt = 0
    status = horse.get("race_status") or ""
    results = horse.get("major_results") or ""
    wins = int(horse.get("wins") or 0)

    # 1. レース単位での戦績ポイント積算
    races = [r.strip() for r in results.split("、") if r.strip()]
    matched_race = False
    for r in races:
        if "1着" in r:
            if "G1" in r or "GI" in r:
                perf_pt += 120
                if any(c in r for c in ("日本ダービー", "オークス", "皐月賞", "桜花賞")):
                    perf_pt += 20
                matched_race = True
            elif "G2" in r or "GII" in r:
                perf_pt += 75
                matched_race = True
            elif "G3" in r or "GIII" in r:
                perf_pt += 55
                matched_race = True
            elif "(L" in r:
                perf_pt += 39
                matched_race = True
            elif "(OP" in r or "(1勝" in r or "1勝クラス" in r:
                perf_pt += 35
                matched_race = True
            elif "新馬" in r or "未勝利" in r:
                perf_pt += 18
                matched_race = True
        elif "2着" in r:
            if "G1" in r or "GI" in r:
                perf_pt += 45
                matched_race = True
            elif "G2" in r or "GII" in r:
                perf_pt += 20
                matched_race = True
            elif "G3" in r or "GIII" in r:
                perf_pt += 12
                matched_race = True
            elif "(L" in r or "(OP" in r or "(1勝" in r:
                perf_pt += 10
                matched_race = True
            elif "新馬" in r or "未勝利" in r:
                perf_pt += 6
                matched_race = True
        elif "3着" in r:
            if "G1" in r or "GI" in r:
                perf_pt += 30
                matched_race = True
            elif "G2" in r or "GII" in r:
                perf_pt += 10
                matched_race = True
            elif "G3" in r or "GIII" in r:
                perf_pt += 6
                matched_race = True
            elif "新馬" in r or "未勝利" in r:
                perf_pt += 3
                matched_race = True

    if not matched_race:
        if status == "OP・1勝クラス勝馬":
            perf_pt += 35
        elif status == "重賞・OP好走":
            perf_pt += 26
        elif status == "新馬・未勝利勝馬":
            perf_pt += 18
        elif status == "出走済(未勝利)":
            perf_pt += 4

    # 複数勝利ボーナス
    if wins >= 2:
        perf_pt += (wins - 1) * 10

    # 圧勝・高指数ボーナス
    if "7馬身差" in results or "高指数" in results:
        perf_pt += 5
    elif "3馬身差" in results or "2馬身差" in results:
        perf_pt += 3

    price = int(horse.get("price_man_yen") or 0)
    if price >= 30000:
        pre_pt += 14
    elif price >= 20000:
        pre_pt += 11
    elif price >= 10000:
        pre_pt += 8
    elif price >= 6000:
        pre_pt += 6
    elif price > 0:
        pre_pt += 4

    if horse.get("selection_source") != "戦績評価(重賞/OP/新馬)":
        pre_pt += 6
    if horse.get("selection_source") == "両方(事前+戦績)":
        pre_pt += 4

    return perf_pt + pre_pt


def update_snapshots(out_dir: Path, merged_horses: list, snapshot_date: str):
    """日付ごとの順位・指数スナップショットを保存・更新する。"""
    snap_path = out_dir / "snapshots_2027.json"
    if snap_path.exists():
        with open(snap_path, "r", encoding="utf-8") as f:
            snapshots = json.load(f)
    else:
        snapshots = {}

    ranked = sorted(
        merged_horses,
        key=lambda h: (
            -calculate_score(h),
            -int(h.get("wins") or 0),
            -int(h.get("price_man_yen") or 0),
            h["name"],
        ),
    )

    sex_counter = {"牡": 0, "牝": 0}
    last_overall_score = None
    last_overall_rank = 0
    last_sex_score = {"牡": None, "牝": None}
    last_sex_rank = {"牡": 0, "牝": 0}

    day_snap = {}
    for idx, h in enumerate(ranked, start=1):
        sex = h["sex"]
        score = calculate_score(h)
        if score != last_overall_score:
            overall_rank = idx
            last_overall_score = score
            last_overall_rank = overall_rank
        else:
            overall_rank = last_overall_rank

        sex_counter[sex] = sex_counter.get(sex, 0) + 1
        if score != last_sex_score.get(sex):
            s_rank = sex_counter[sex]
            last_sex_score[sex] = score
            last_sex_rank[sex] = s_rank
        else:
            s_rank = last_sex_rank[sex]

        day_snap[h["netkeiba_id"]] = {
            "rank": overall_rank,
            "sex_rank": s_rank,
            "score": score,
            "race_status": h.get("race_status", ""),
            "starts": h.get("starts"),
            "wins": h.get("wins"),
        }

    snapshots[snapshot_date] = day_snap
    # 日付昇順で保存
    ordered = {k: snapshots[k] for k in sorted(snapshots.keys())}
    with open(snap_path, "w", encoding="utf-8") as f:
        json.dump(ordered, f, ensure_ascii=False, indent=2)

    return ordered


