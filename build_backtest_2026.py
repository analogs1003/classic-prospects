def main():
    dates = ["2025-11-08", "2025-12-28", "2026-05-31"]
    snapshots = {}

    for d in dates:
        day_list = []
        for h in HORSES_2026:
            state = dict(h)
            state.update(h["timeline"][d])
            day_list.append(state)

        day_list.sort(
            key=lambda x: (
                -calculate_score(x),
                -int(x.get("wins") or 0),
                -int(x.get("price_man_yen") or 0),
                x["name"],
            )
        )
        sex_cnt = {"牡": 0, "牝": 0}
        last_overall_score = None
        last_overall_rank = 0
        last_sex_score = {"牡": None, "牝": None}
        last_sex_rank = {"牡": 0, "牝": 0}

        day_snap = {}
        for idx, x in enumerate(day_list, start=1):
            sex = x["sex"]
            score = calculate_score(x)
            if score != last_overall_score:
                overall_rank = idx
                last_overall_score = score
                last_overall_rank = overall_rank
            else:
                overall_rank = last_overall_rank

            sex_cnt[sex] += 1
            if score != last_sex_score[sex]:
                s_rank = sex_cnt[sex]
                last_sex_score[sex] = score
                last_sex_rank[sex] = s_rank
            else:
                s_rank = last_sex_rank[sex]

            day_snap[x["netkeiba_id"]] = {
                "rank": overall_rank,
                "sex_rank": s_rank,
                "score": score,
                "race_status": x["race_status"],
                "starts": x["starts"],
                "wins": x["wins"],
            }
        snapshots[d] = day_snap

    # 最終時点 (2026-05-31) を現在値として格納
    final_horses = []
    for h in HORSES_2026:
        item = {k: v for k, v in h.items() if k != "timeline"}
        item.update(h["timeline"]["2026-05-31"])
        final_horses.append(item)

    out_dir = Path("data")
    out_dir.mkdir(exist_ok=True)
    js_path = out_dir / "classic_2026_prospects.js"
    payload = {
        "generation_id": "2026",
        "season_label": "2026クラシック世代（現3歳・2023年産）",
        "period_label": "2025年11月〜2026年5月 ダービー・オークス（検証用）",
        "updated_at": "2026-05-31 (確定)",
        "horses": final_horses,
        "snapshots": snapshots,
    }
    with open(js_path, "w", encoding="utf-8") as f:
        f.write("window.CLASSIC_GENERATIONS = window.CLASSIC_GENERATIONS || {};\n")
        f.write('window.CLASSIC_GENERATIONS["2026"] = ')
        json.dump(payload, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    print(f"Generated 2026 backtest JS: {js_path} ({len(final_horses)} horses)")
    for d in dates:
        top5 = sorted(snapshots[d].items(), key=lambda kv: kv[1]["rank"])[:5]
        names = {h["netkeiba_id"]: h["name"] for h in final_horses}
        print(f"[{d}] Top5:", [(names[k], v["rank"], v["score"]) for k, v in top5])


if __name__ == "__main__":
    main()

